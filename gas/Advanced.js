/** 応用編の項目がまだなければ足す（setup とアプリを開いたときに呼ぶ） */
function ensureAdvanced_() {
  var p = props_();
  if (!ADVANCED_SEEDS.some(function (s) { return !p.getProperty(s.key); })) return;
  withLock_(function () {
    var t = EDIT_TARGET.task;
    ADVANCED_SEEDS.forEach(function (seed) {
      if (p.getProperty(seed.key)) return;
      var tasks = readRows_(t);
      if (!tasks.some(function (r) { return String(r[5]) === seed.mode; })) {
        seed.items.forEach(function (it) {
          tasks.push([nextId_(t, tasks), seed.phase, it[0], it[1], it[2], seed.mode]);
        });
        writeRows_(t, tasks);
      }
      p.setProperty(seed.key, '1');
    });
  });
}
